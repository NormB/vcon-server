"""Finds text that must never be committed.

Reads lines of the form "<path>\t<text>" on standard input and prints one
line per finding. Exits 1 if anything was found, else 0, and 2 if it could
not scan. A line that is not UTF-8 is scanned too (see `decode`). The same rules
scan staged lines, staged paths and commit messages, so they live only here.

Patterns that name forbidden words are written so that this file does not
match itself, for example "(c)laude".
"""

import ipaddress
import os
import pathlib
import re
import subprocess
import sys

# Other AI assistants are refused where they take credit: a co-author
# trailer or a "generated with/by" line. Elsewhere the words have ordinary
# meanings (an editor's cursor, "generated by the build"). The same list
# as kamailio-lsp's and opensips-lsp's scripts/attribution-scan.py.
AI_TOOLS = r"(c[o]pilot|chatg[p]t|open[a]i|gpt-?\d|gem[i]ni|cod[e]x|curs[o]r|dev[i]n|aid[e]r|ai|llm|assistant)"

AI_ATTRIBUTION = [
    ("AI tool name", re.compile(r"\b(c)laude\b", re.I)),
    ("AI company name", re.compile(r"\ba(n)thropic\b", re.I)),
    ("robot emoji", re.compile("\U0001F916")),
    ("AI co-author trailer", re.compile(r"co-authored-(b)y:.*\b" + AI_TOOLS + r"\b", re.I)),
    ("generated-with footer", re.compile(r"\bgenerated (?:(w)ith|by)\b.*\b" + AI_TOOLS + r"\b", re.I)),
]

OWNER = [("owner's name", re.compile(r"\b(b)randinger\b", re.I))]

# The owner asked to be credited, as on sipnab.com, in the README and in
# the site's configuration, which the page footer reads. Nowhere else.
OWNER_CREDIT_PATHS = {"README.md", "website/config.toml"}

# Every id takes any number of digits: the documents keep growing, and an id
# past the first phases or past 99 is as private as the first ones.
PRIVATE_DOC_IDS = [
    # Any case, joined by - or _, so an id inside a snake_case name is
    # caught too; \b would not split _ from a letter, so the edges are
    # spelled out.
    (
        "design rule id",
        re.compile(r"(?<![A-Za-z0-9])(?:FMT|ENV|STO|ACC|AUD|API|OPS|TEN|BKD)[-_][0-9]+(?![0-9])", re.I),
    ),
    ("design decision id", re.compile(r"\bCD[0-9]+\b")),
    ("scope decision id", re.compile(r"\bD[1-9][0-9]*\b")),
    ("plan task id", re.compile(r"\bP[0-9]+\.[0-9]+\b")),
    ("private draft number", re.compile(r"\bdraft\s+[0-9]+\.[0-9]+\b", re.I)),
]

# The local part may hold `[` and `]`, as a GitHub bot's noreply alias does
# (`<ID>+dependabot[bot]` at `users.noreply.github.com`); without them the
# pattern could not start a match at `]@`, and `x]@` before any domain passed.
EMAIL = re.compile(r"[A-Za-z0-9._%+\[\]-]+@([A-Za-z0-9-]+(?:\.[A-Za-z0-9-]+)+)")
RESERVED_DOMAINS = ("example.com", "example.net", "example.org")
# Addresses of GitHub's own services, not of a person: Dependabot signs
# its commits "Signed-off-by: dependabot[bot] <support@github.com>".
# Exact addresses only; anyone else at github.com is still found.
SERVICE_ADDRESSES = ("support@github.com",)
RESERVED_TLDS = (".example", ".invalid", ".test", ".localhost")

# GitHub's private commit address: `<ID>+<login>@users.noreply.github.com`,
# or `<login>@users.noreply.github.com` for an older account; a bot's login
# ends in `[bot]`. A login is letters, digits and single inner hyphens, at most
# 39 characters. It is GitHub's alias, not a person's address, so a
# contributor's DCO sign-off can name it (CONTRIBUTING.md, "Signing off
# commits"): on a Signed-off-by line of a commit message only, and only as
# the whole address. scripts/check_dco.py reads the same rule.
GITHUB_NOREPLY = re.compile(
    r"(?:[0-9]+\+)?[A-Za-z0-9](?:[A-Za-z0-9-]{0,37}[A-Za-z0-9])?(?:\[bot\])?@users\.noreply\.github\.com",
    re.IGNORECASE,
)
COMMIT_MESSAGE = "<commit message>"
NOREPLY_SIGN_OFF = re.compile(
    r"signed-off-by:[ \t]*[^<\r\n]*?[ \t]*<(" + GITHUB_NOREPLY.pattern + r")>[ \t]*\r?",
    re.IGNORECASE,
)


def is_noreply(address):
    """Whether `address`, whole, is a GitHub noreply address."""
    return GITHUB_NOREPLY.fullmatch(address) is not None


def allowed_address_span(path, text):
    """Where the one address a line may hold is: the noreply address of a
    commit message line that is a whole Signed-off-by line; else None."""
    if path != COMMIT_MESSAGE:
        return None
    m = NOREPLY_SIGN_OFF.fullmatch(text)
    return m.span(1) if m else None

PHONE_NANP = re.compile(r"(?<![\d.])(?:\+?1[\s.-]?)?\(?([2-9]\d{2})\)?[\s.-](\d{3})[\s.-](\d{4})(?![\d.])")
PHONE_E164 = re.compile(r"(?<![\w+])\+([1-9]\d{7,14})\b")

IPV4 = re.compile(r"(?<![\d.])(\d{1,3}(?:\.\d{1,3}){3})(?![\d.])")
IPV6 = re.compile(r"(?<![0-9A-Za-z:])((?:[0-9A-Fa-f]{0,4}:){2,7}[0-9A-Fa-f]{0,4})(?![0-9A-Za-z:])")
DOC_NETS_V4 = [ipaddress.ip_network(n) for n in ("192.0.2.0/24", "198.51.100.0/24", "203.0.113.0/24", "127.0.0.0/8")]
DOC_NET_V6 = ipaddress.ip_network("2001:db8::/32")


# What comes before the `[` of an index or a slice: a name, or the `)` or
# `]` that closes a call or another index. On 2026-11-26 the IPv6 rule took
# `argv[1::2]` in a Python script for an address; an address in
# brackets follows a `/`, a space, an `=` or a quote instead.
INDEXED = re.compile(r"[0-9A-Za-z_)\]]")


def is_slice(text, start, end):
    """Whether the run text[start:end] fills the brackets of an index or a
    slice: `[` right before it, `]` right after, and before the `[`
    something that can be indexed."""
    return (
        start >= 2
        and text[start - 1] == "["
        and text[end : end + 1] == "]"
        and INDEXED.fullmatch(text[start - 2]) is not None
    )


def reserved_domain(domain):
    d = domain.lower()
    return d in RESERVED_DOMAINS or d.endswith(RESERVED_TLDS) or any(d.endswith("." + r) for r in RESERVED_DOMAINS)


# The two illustrative numbers in the IETF vCon core draft's examples, which
# are kept byte for byte as test fixtures. Allowed only in those fixtures.
IETF_EXAMPLE_PHONES = {"+1234567" "8901", "+1987654" "3210"}


def is_ietf_fixture(path):
    return "/tests/fixtures/ietf/" in "/" + path


def reserved_phone(exchange, line):
    return exchange == "555" and line.startswith("01")


def personal_data(text, path=""):
    allowed = allowed_address_span(path, text)
    for m in EMAIL.finditer(text):
        if m.span() == allowed:
            continue
        if not reserved_domain(m.group(1)) and m.group(0).lower() not in SERVICE_ADDRESSES:
            yield "email address", m.group(0)
    for m in PHONE_NANP.finditer(text):
        if not reserved_phone(m.group(2), m.group(3)):
            yield "phone number", m.group(0)
    for m in PHONE_E164.finditer(text):
        digits = m.group(1)
        if is_ietf_fixture(path) and m.group(0) in IETF_EXAMPLE_PHONES:
            continue
        if not (len(digits) == 11 and digits[0] == "1" and digits[4:7] == "555" and digits[7:9] == "01"):
            yield "phone number", m.group(0)
    for m in IPV4.finditer(text):
        try:
            ip = ipaddress.IPv4Address(m.group(1))
        except ValueError:
            continue
        if str(ip) == "0.0.0.0" or any(ip in n for n in DOC_NETS_V4):
            continue
        yield "IP address", m.group(1)
    for m in IPV6.finditer(text):
        candidate = m.group(1)
        if candidate.count(":") < 2 or not re.search(r"[0-9]", candidate):
            continue
        if is_slice(text, m.start(1), m.end(1)):
            continue
        try:
            ip = ipaddress.IPv6Address(candidate)
        except ValueError:
            continue
        if ip.is_loopback or ip in DOC_NET_V6:
            continue
        yield "IP address", candidate


def is_fixture(path):
    return "/fixtures/" in "/" + path


def scan(path, text):
    rules = AI_ATTRIBUTION if path in OWNER_CREDIT_PATHS else AI_ATTRIBUTION + OWNER
    for reason, pattern in rules:
        if pattern.search(text):
            yield reason, pattern.search(text).group(0)
    yield from personal_data(text, path)
    if not is_fixture(path):
        for reason, pattern in PRIVATE_DOC_IDS:
            m = pattern.search(text)
            if m:
                yield reason, m.group(0)


def decode(raw):
    """The text of one input line, and whether it was UTF-8. A file git
    takes for text can hold bytes that are not UTF-8 (another encoding, or a
    binary file with no NUL byte). Each such byte reads as U+FFFD, which is
    not a word character, so a word beside it is still found."""
    try:
        return raw.decode("utf-8"), True
    except UnicodeDecodeError:
        return raw.decode("utf-8", errors="replace"), False


def main(stdin, out, err):
    """Scans the "<path>\\t<text>" lines of the byte stream `stdin`; prints
    each finding on `out` and, once per path, a note on `err` for a line
    that is not UTF-8. 1 if anything was found, else 0."""
    found = False
    noted = set()
    for raw in stdin:
        line, utf8 = decode(raw.rstrip(b"\n"))
        path, _, text = line.partition("\t")
        if not utf8 and path not in noted:
            noted.add(path)
            print(f"{path}: not UTF-8: scanned with U+FFFD for each byte that is not", file=err)
        for reason, hit in scan(path, text):
            found = True
            print(f"{path}: {reason}: {hit!r}", file=out)
    return 1 if found else 0


# A trailer is published on main with its commit. The project's policy
# (CONTRIBUTING.md, "Personal data in commit messages") allows an email
# address in a commit only in its author and committer fields, so no trailer
# names one, not even a reserved one. Two forms name no person and stay
# allowed: a whole Signed-off-by trailer naming a GitHub noreply address, the
# DCO sign-off a contributor makes (NOREPLY_SIGN_OFF), and GitHub's service
# addresses (SERVICE_ADDRESSES), which Dependabot signs with.
TRAILER_ADDRESS = "email address in a trailer"

# The comment character for the reading of a message stored whole: a
# control character no line starts with, so `#` lines and a scissors line
# are text, as git commit -m and -F keep them.
NO_COMMENT_CHAR = "\x01"


def trailer_env(environ):
    """The environment `git interpret-trailers` runs in: `environ` without
    any repository or configuration git would read. A `trailer.*` setting
    changes which lines are trailers, and a commit-msg hook runs with the
    repository's GIT_DIR set, so the verdict would differ by machine."""
    env = {k: v for k, v in environ.items() if k not in ("GIT_DIR", "GIT_WORK_TREE", "GIT_CONFIG_PARAMETERS", "GIT_CONFIG_COUNT")}
    env["GIT_CONFIG_NOSYSTEM"] = "1"
    env["GIT_CONFIG_GLOBAL"] = os.devnull
    return env


def git_trailers(message, comment_char=None, git="git"):
    """The trailers of `message`, one per line with folded lines joined, as
    `git interpret-trailers --parse --no-divider` reads them. `--no-divider`
    reads past a `---` line, as git commit does; Dependabot's bodies hold one.
    `comment_char` None keeps git's own `#` comments and scissors line.
    Raises OSError when git does not start and RuntimeError when it fails:
    a message nobody read is not a clean message."""
    args = [git]
    if comment_char is not None:
        args += ["-c", f"core.commentChar={comment_char}"]
    args += ["interpret-trailers", "--parse", "--no-divider"]
    proc = subprocess.run(
        args,
        input=message.encode("utf-8", errors="surrogateescape"),
        capture_output=True,
        cwd="/",
        env=trailer_env(os.environ),
        timeout=60,
        check=False,
    )
    if proc.returncode != 0:
        raise RuntimeError(f"git interpret-trailers failed ({proc.returncode}): {proc.stderr.decode(errors='replace').strip()}")
    return proc.stdout.decode("utf-8", errors="replace").splitlines()


def trailer_names_an_address(trailer):
    """Whether one trailer, as git unfolds it, names an address it may not."""
    allowed = None
    m = NOREPLY_SIGN_OFF.fullmatch(trailer)
    if m:
        allowed = m.span(1)
    for e in EMAIL.finditer(trailer):
        if e.span() == allowed or e.group(0).lower() in SERVICE_ADDRESSES:
            continue
        return True
    return False


def trailer_findings(message, git="git"):
    """Each trailer of the commit message `message` that names an address.
    The hook reads every line, `#` lines too, so both readings count: with
    git's `#` comments and scissors line, as for a message edited in an
    editor, and with none, as git commit -m and -F store it. Each trailer is
    named once, in order."""
    seen = []
    for comment_char in (None, NO_COMMENT_CHAR):
        for trailer in git_trailers(message, comment_char, git):
            if trailer not in seen and trailer_names_an_address(trailer):
                seen.append(trailer)
    return [(TRAILER_ADDRESS, t) for t in seen]


def message_findings(message, git="git"):
    """Every finding in the commit message `message`: each line, as
    <commit message>, then its trailers."""
    found = []
    for line in message.splitlines():
        found += list(scan(COMMIT_MESSAGE, line))
    return found + trailer_findings(message, git)


def scan_message_file(path, stdin, out, err):
    """`--commit-message FILE` (`-` for standard input): prints each finding
    in the message; 1 if anything was found, else 0. A message that is not
    UTF-8 is scanned with U+FFFD for each such byte, and noted on `err`."""
    data = stdin.read() if path == "-" else pathlib.Path(path).read_bytes()
    text, utf8 = decode(data)
    if not utf8:
        print(f"{COMMIT_MESSAGE}: not UTF-8: scanned with U+FFFD for each byte that is not", file=err)
    found = message_findings(text)
    for reason, hit in found:
        print(f"{COMMIT_MESSAGE}: {reason}: {hit!r}", file=out)
    return 1 if found else 0


def run(stdin, out, err, argv=()):
    """main, or `--commit-message FILE` when `argv` says so, with a scan that
    cannot run answered 2: an exit of 1 would read as a finding, and no scan
    took place."""
    try:
        if list(argv[:1]) == ["--commit-message"]:
            if len(argv) != 2:
                raise ValueError("usage: scan_forbidden.py --commit-message FILE|-")
            return scan_message_file(argv[1], stdin, out, err)
        if argv:
            raise ValueError(f"unknown arguments {list(argv)!r}")
        return main(stdin, out, err)
    except Exception as error:  # noqa: BLE001 - any failure is "no verdict"
        print(f"scan_forbidden: cannot scan: {error}", file=err)
        return 2


def utf8_out(*streams):
    """Each text stream writes UTF-8 whatever the locale, and a character
    UTF-8 cannot hold (a lone surrogate) as an escape: no finding fails to
    print."""
    for stream in streams:
        stream.reconfigure(encoding="utf-8", errors="backslashreplace")


if __name__ == "__main__":
    utf8_out(sys.stdout, sys.stderr)
    sys.exit(run(sys.stdin.buffer, sys.stdout, sys.stderr, sys.argv[1:]))
