        try:
            self.assertEqual(trailer_hits("Fix it\n\nBody.\n\nCc= someone@example.com\n"), [])
        finally:
            if saved is None:
                del os.environ["GIT_CONFIG_PARAMETERS"]
            else:
                os.environ["GIT_CONFIG_PARAMETERS"] = saved

