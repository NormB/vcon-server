"""Tests the AI-attribution rule in scripts/scan_forbidden.py: any AI
assistant credited in a co-author trailer or a "generated with/by" line is
refused, on every line, # lines and lines below a scissors line included;
the same words in their ordinary meaning pass.

The tool names are assembled at run time, so this file holds none whole.

Run with: python3 -I scripts/test_scan_forbidden.py
"""

import importlib.util
import pathlib
import sys
import unittest

# Loading a script by path would otherwise leave a __pycache__ beside it.
sys.dont_write_bytecode = True
HERE = pathlib.Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location("scan_forbidden", HERE / "scan_forbidden.py")
scan_forbidden = importlib.util.module_from_spec(spec)
spec.loader.exec_module(scan_forbidden)

COPILOT = "Co" + "pilot"
TOOLS = [COPILOT, "Chat" + "GPT", "Open" + "AI", "GPT" + "-4", "GPT" + "5", "Gem" + "ini", "Co" + "dex", "Cur" + "sor", "De" + "vin", "Ai" + "der"]
TRAILER = "Co-Authored" + "-By"


def message(text):
    """The findings for a commit message, read the way the commit-msg hook
    and scan-commit-messages.sh read one: every line, as <commit message>."""
    found = []
    for line in text.splitlines():
        found += list(scan_forbidden.scan("<commit message>", line))
    return found


class Trailers(unittest.TestCase):
    def test_a_copilot_co_author_trailer_is_refused(self):
        self.assertTrue(message(f"Fix it\n\n{TRAILER}: GitHub {COPILOT} <c@example.invalid>"))

    def test_the_same_trailer_on_a_hash_line_is_refused(self):
        self.assertTrue(message(f"Fix it\n\n# {TRAILER}: GitHub {COPILOT} <c@example.invalid>"))

    def test_the_same_trailer_below_a_scissors_line_is_refused(self):
        scissors = "# ------------------------ >8 ------------------------"
        self.assertTrue(message(f"Fix it\n{scissors}\n{TRAILER}: GitHub {COPILOT} <c@example.invalid>"))

    def test_every_listed_tool_in_a_trailer_is_refused(self):
        for tool in TOOLS:
            with self.subTest(tool=tool):
                self.assertTrue(message(f"{TRAILER}: {tool} <x@example.invalid>"))

    def test_a_bare_ai_in_a_trailer_is_refused(self):
        self.assertTrue(message(f"{TRAILER}: A" + "I helper <x@example.invalid>"))

    def test_a_person_as_co_author_passes(self):
        self.assertEqual(message(f"{TRAILER}: Jane Doe <jane@example.com>"), [])


class Footers(unittest.TestCase):
    def test_generated_with_or_by_a_tool_is_refused(self):
        for verb in ("with", "by"):
            for tool in TOOLS:
                with self.subTest(verb=verb, tool=tool):
                    self.assertTrue(message(f"Generated {verb} {tool}"))

    def test_generated_by_the_build_passes(self):
        self.assertEqual(message("generated by the build from openapi.json"), [])

    def test_generated_with_a_tool_that_is_not_an_assistant_passes(self):
        self.assertEqual(message("the site is generated with zola"), [])

    def test_a_tool_named_by_without_generated_passes(self):
        # Only "generated with/by" takes credit; "by" alone does not.
        self.assertEqual(message("filed by the " + "ai" + " team lead, reviewed by people"), [])


class OrdinaryWords(unittest.TestCase):
    def test_the_words_in_their_ordinary_meaning_pass(self):
        for text in ("move the " + "cur" + "sor to the end", "an " + "ai" + "der of the build", "said the maintainer"):
            with self.subTest(text=text):
                self.assertEqual(message(text), [])


if __name__ == "__main__":
    unittest.main()
